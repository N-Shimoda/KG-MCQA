import pytest

from tools import select_best_answer


@pytest.mark.parametrize(
    "scores, expected",
    [
        # 単純なケース: エッジスコアが一意
        ([(0.8, 0.5), (0.6, 0.7), (0.9, 0.4), (0.7, 0.6)], 2),
        # エッジスコアが同点、ノードスコアで決定
        ([(0.8, 0.5), (0.8, 0.7), (0.6, 0.4), (0.7, 0.6)], 1),
        # エッジスコアとノードスコアが同点でタイ
        ([(0.8, 0.5), (0.8, 0.5), (0.6, 0.4), (0.7, 0.6)], -1),
        # 全てのスコアが同じ
        ([(0.5, 0.5), (0.5, 0.5), (0.5, 0.5), (0.5, 0.5)], -1),
        # スコアが1つだけ
        ([(0.9, 0.7)], 0),
        # ノードスコアが一意で決定
        ([(0.8, 0.5), (0.8, 0.6), (0.8, 0.4), (0.8, 0.3)], 1),
    ],
)
def test_select_best_answer(scores, expected):
    assert select_best_answer(scores) == expected
